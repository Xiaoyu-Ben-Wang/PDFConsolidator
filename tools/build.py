"""Build the standalone distribution.

Steps:

1. Freeze the application with PyInstaller (``--onedir``, never ``--onefile``:
   onefile re-extracts ~250 MB of Qt to a temp directory on every launch).
2. Copy a trimmed LibreOffice beside it, so the result converts Office documents
   on a machine that has none installed.
3. Copy the licence material - ``LICENSE``, ``THIRD-PARTY-NOTICES.md`` and the
   verbatim texts in ``LICENSES/`` - so the licences travel with the binaries.
   Regenerated by ``tools/collect_licenses.py`` when it is missing.
4. Report the size, what was trimmed, and whether the notices still cover
   everything that was frozen.

Trimming removes only material that a conversion engine never touches: help
files, the spell-check dictionaries, clipart, document templates and the
translation XSLTs. Everything needed to render a document is kept.

Usage::

    python tools/build.py [--out dist] [--skip-libreoffice] [--no-trim]
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_LO = Path(r"C:\Program Files\LibreOffice")

# Directories inside the LibreOffice tree that conversion never needs.
TRIM_PATHS = [
    "help",
    "readmes",
    "share/extensions",   # spell-check and hyphenation dictionaries
    "share/gallery",      # clipart
    "share/template",     # document templates for new files
    "share/wizards",
    "share/xslt",
    "share/autotext",
    "share/autocorr",
    # Only used to benchmark OpenCL devices - and it caches a read-only lock
    # file inside the bundle, which then blocks the next build's cleanup.
    "program/opencl",
]


def force_remove(path: Path) -> None:
    """Remove a tree, clearing read-only attributes first.

    LibreOffice marks its ``.~lock.*#`` files read-only, and Windows refuses to
    delete a read-only file, so a plain ``rmtree`` fails with ``WinError 5``.
    Running the bundled LibreOffice leaves exactly such a file behind, which is
    what breaks a subsequent rebuild.
    """
    if not path.exists():
        return
    for root, _dirs, files in os.walk(path):
        for name in files:
            try:
                os.chmod(os.path.join(root, name), 0o666)
            except OSError:
                pass
    shutil.rmtree(path, ignore_errors=True)
    if path.exists():
        time.sleep(1.0)          # a handle may still be closing
        for root, _dirs, files in os.walk(path):
            for name in files:
                try:
                    os.chmod(os.path.join(root, name), 0o666)
                except OSError:
                    pass
        shutil.rmtree(path, ignore_errors=True)


def directory_size(path: Path) -> int:
    total = 0
    for root, _dirs, files in os.walk(path):
        for name in files:
            try:
                total += os.path.getsize(os.path.join(root, name))
            except OSError:
                pass
    return total


def human(num_bytes: int) -> str:
    value = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB"):
        if value < 1024 or unit == "GB":
            return "%.1f %s" % (value, unit)
        value /= 1024.0
    return "%.1f GB" % value


def run_pyinstaller(out_dir: Path) -> Path:
    cmd = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean",
        "--onedir", "--windowed",
        "--name", "PDFConsolidator",
        "--distpath", str(out_dir),
        "--workpath", str(ROOT / "build" / "_work"),
        "--specpath", str(ROOT / "build"),
        "--paths", str(ROOT / "src"),
        # Sets the Properties -> Details fields; the publisher Windows shows in
        # SmartScreen and UAC comes from the signature applied below.
        "--version-file", str(ROOT / "build" / "version_info.txt"),
        # Not used, and each pulls in a large Qt module.
        "--exclude-module", "PySide6.QtWebEngineCore",
        "--exclude-module", "PySide6.QtWebEngineWidgets",
        "--exclude-module", "PySide6.QtQml",
        "--exclude-module", "PySide6.QtQuick",
        "--exclude-module", "PySide6.Qt3DCore",
        "--exclude-module", "PySide6.QtCharts",
        "--exclude-module", "PySide6.QtDataVisualization",
        "--exclude-module", "PySide6.QtMultimedia",
        "--exclude-module", "tkinter",
        "--exclude-module", "matplotlib",
        str(ROOT / "build" / "consolidator_gui.py"),
    ]
    print("running PyInstaller ...", flush=True)
    result = subprocess.run(cmd, cwd=str(ROOT))
    if result.returncode != 0:
        raise SystemExit("PyInstaller failed with code %d" % result.returncode)
    bundle = out_dir / "PDFConsolidator"
    if not bundle.exists():
        raise SystemExit("PyInstaller produced no bundle at %s" % bundle)
    return bundle


def copy_libreoffice(bundle: Path, source: Path, trim: bool) -> int:
    if not source.exists():
        print("WARNING: LibreOffice not found at %s - the bundle will need it "
              "installed on the target machine" % source)
        return 0

    destination = bundle / "libreoffice"
    if destination.exists():
        print("removing previous LibreOffice copy ...", flush=True)
        force_remove(destination)

    print("copying LibreOffice from %s ..." % source, flush=True)
    shutil.copytree(source, destination, dirs_exist_ok=True, symlinks=False)

    freed = 0
    if trim:
        for relative in TRIM_PATHS:
            target = destination / relative
            if target.exists():
                before = directory_size(target)
                shutil.rmtree(target, ignore_errors=True)
                freed += before
                print("  trimmed %-22s %s" % (relative, human(before)))

    soffice = destination / "program" / "soffice.exe"
    if not soffice.exists():
        raise SystemExit("LibreOffice copy is missing program/soffice.exe")
    print("  LibreOffice bundled: %s" % human(directory_size(destination)))
    if freed:
        print("  trimmed away      : %s" % human(freed))
    return freed


def copy_licences(bundle: Path) -> int:
    """Put the licence material beside the executable.

    The bundle redistributes Qt, LibreOffice and a pile of libraries, and their
    licences have to travel with it. ``tools/collect_licenses.py`` produces the
    texts and the notices; this only copies what it produced, regenerating it if
    it is missing so a fresh clone cannot ship without it.
    """
    collector = ROOT / "tools" / "collect_licenses.py"
    notices = ROOT / "THIRD-PARTY-NOTICES.md"
    licences = ROOT / "LICENSES"

    if not notices.exists() or not licences.exists():
        print("licence material missing; collecting it ...", flush=True)
        subprocess.run([sys.executable, str(collector)], cwd=str(ROOT))

    copied = 0
    for source, destination in ((ROOT / "LICENSE", bundle / "LICENSE"),
                                (notices, bundle / "THIRD-PARTY-NOTICES.md")):
        if source.exists():
            shutil.copyfile(source, destination)
            copied += 1
        else:
            print("WARNING: %s is missing - the bundle will ship without it"
                  % source.name)
    if licences.exists():
        target = bundle / "LICENSES"
        force_remove(target)
        shutil.copytree(licences, target)
        copied += 1
    return copied


def check_licences(exe: Path) -> None:
    """Warn if the bundle holds a component the notices do not mention.

    A new dependency silently gaining a licence obligation is exactly the kind of
    thing no one notices until it matters, so the build checks it every time.
    """
    result = subprocess.run(
        [sys.executable, str(ROOT / "tools" / "collect_licenses.py"),
         "--verify", str(exe)],
        cwd=str(ROOT),
    )
    if result.returncode != 0:
        print()
        print("WARNING: the notices do not cover everything in the bundle - see "
              "above. Ship it only once tools/collect_licenses.py has been "
              "updated.")


def sign_executable(exe: Path, publisher: str, trust: bool) -> bool:
    """Sign the executable so Windows names the publisher instead of 'unknown'.

    Without an Authenticode signature the publisher is reported as unknown, and
    there is no setting that simply declares one - the file must be signed. See
    tools/sign.ps1 for what a self-signed certificate does and does not buy.
    """
    script = ROOT / "tools" / "sign.ps1"
    if not script.exists():
        print("WARNING: tools/sign.ps1 not found; skipping signing")
        return False

    cmd = [
        "powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
        "-File", str(script),
        "-Path", str(exe),
        "-Publisher", publisher,
    ]
    if trust:
        cmd.append("-Trust")

    print("signing as %r ..." % publisher, flush=True)
    result = subprocess.run(cmd, cwd=str(ROOT))
    if result.returncode != 0:
        print("WARNING: signing failed with code %d" % result.returncode)
        return False
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(ROOT / "dist"), help="output directory")
    parser.add_argument("--libreoffice", default=str(DEFAULT_LO),
                        help="LibreOffice installation to bundle")
    parser.add_argument("--skip-libreoffice", action="store_true")
    parser.add_argument("--no-trim", action="store_true")
    parser.add_argument("--publisher", default="Xiaoyu-Ben-Wang",
                        help="publisher name to sign with (default: %(default)s)")
    parser.add_argument("--no-sign", action="store_true",
                        help="skip signing the executable")
    parser.add_argument("--trust", action="store_true",
                        help="also trust the certificate locally (needs administrator)")
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    started = time.monotonic()

    # Clear any previous bundle before PyInstaller tries to clean it, since it
    # does not cope with the read-only lock files LibreOffice leaves behind.
    force_remove(out_dir / "PDFConsolidator")

    bundle = run_pyinstaller(out_dir)
    print("application bundle: %s" % human(directory_size(bundle)))

    if not args.skip_libreoffice:
        copy_libreoffice(bundle, Path(args.libreoffice), trim=not args.no_trim)

    print("licence material: %d item(s) copied beside the executable"
          % copy_licences(bundle))

    exe = bundle / "PDFConsolidator.exe"
    if not args.no_sign:
        sign_executable(exe, args.publisher, args.trust)

    check_licences(exe)

    total = directory_size(bundle)
    print()
    print("=" * 68)
    print("Bundle    : %s" % bundle)
    print("Size      : %s" % human(total))
    print("Exe       : %s" % exe)
    print("Publisher : %s" % (args.publisher if not args.no_sign else "(not signed)"))
    print("Time      : %.1fs" % (time.monotonic() - started))
    print("=" * 68)
    print()
    print("Copy that whole folder to the target machine and run")
    print("PDFConsolidator.exe. No installer, no Python, no Office needed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
